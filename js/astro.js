    // ลองจิจูดปรากฏของดวงอาทิตย์ (องศา) ที่ JDE (เวลา TT)
    function sunApparentLongitude(jde) {
        const tau = (jde - 2451545) / 365250, T = tau * 10;
        const L = (sum(L0, tau) + sum(L1, tau) * tau + sum(L2, tau) * tau ** 2 + sum(L3, tau) * tau ** 3 + sum(L4, tau) * tau ** 4 + sum(L5, tau) * tau ** 5) / 1e8;
        const R = (sum(R0, tau) + sum(R1, tau) * tau + sum(R2, tau) * tau ** 2) / 1e8;
        let lon = norm360(L / D2R + 180);
        lon -= 0.09033 / 3600;                                  // แปลงเข้า FK5
        const om = (125.04452 - 1934.136261 * T) * D2R;
        const Ls = (280.4665 + 36000.7698 * T) * D2R, Lm = (218.3165 + 481267.8813 * T) * D2R;
        const dpsi = -17.20 * Math.sin(om) - 1.32 * Math.sin(2 * Ls) - 0.23 * Math.sin(2 * Lm) + 0.21 * Math.sin(2 * om);
        lon += dpsi / 3600 - 20.4898 / 3600 / R;                // nutation + aberration
        return { lon: norm360(lon), dpsi, T };
    }

    // ---------- สารท ----------
    // ลองจิจูดของสารทในเดือนเกรกอเรียน m: type 0 = 节 (ต้นเดือน), 1 = 中气 (กลางเดือน)
    const termLongitude = (m, type) => norm360(285 + (m - 1) * 30 + type * 15);

    const cache = new Map();
    // เวลาเกิดสารท (JD ตามเวลา UT)
    function solarTermUT(year, month, type) {
        const key = year * 100 + month * 2 + type;
        if (cache.has(key)) return cache.get(key);
        const target = termLongitude(month, type);
        let jde = toJD(year, month, 6 + 15 * type, 0) + deltaT(year) / 86400;
        for (let i = 0; i < 20; i++) {
            const d = ((target - sunApparentLongitude(jde).lon + 540) % 360) - 180;
            jde += d * 365.2422 / 360;
            if (Math.abs(d) < 1e-7) break;
        }
        const ut = jde - deltaT(year + (month - 0.5) / 12) / 86400;
        cache.set(key, ut);
        return ut;
    }

