        '正财': { zh: '正财格', th: 'โครงสร้างโชคลาภ', mean: 'ชีวิตสร้างฐานะจากงานประจำและความขยัน เหมาะกับงานที่ผลตอบแทนชัดเจน การบริหารเงิน และทรัพย์สิน' },
        '偏财': { zh: '偏财格', th: 'โครงสร้างโชคลอย', mean: 'ชีวิตหาเงินจากโอกาสและเครือข่าย เหมาะกับการค้า การขาย การลงทุน และงานที่เคลื่อนไหว' },
